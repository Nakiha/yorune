// 解析地图字符串为二维数组
function parseMapString(mapStr) {
    const lines = mapStr.trim().split('\n');
    const map = [];
    
    for (let line of lines) {
        const row = [];
        for (let char of line) {
            row.push(char);
        }
        map.push(row);
    }
    
    return map;
}

